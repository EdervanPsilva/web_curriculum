function getNestedValue(obj, path) {
  return path.split('.').reduce((acc, key) => (acc ? acc[key] : undefined), obj);
}

function applyLanguage(lang) {
  const page = document.body.dataset.page;
  const selected = translations[lang] ? lang : 'en';
  const data = translations[selected];

  document.documentElement.lang = selected === 'pt' ? 'pt-BR' : 'en';
  document.title = data.titles[page] || data.titles.home;

  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.dataset.i18n;
    const value = getNestedValue(data, key);
    if (typeof value === 'string') {
      el.textContent = value;
    }
  });

  document.querySelectorAll('[data-i18n-attr]').forEach((el) => {
    const rules = el.dataset.i18nAttr.split(',');
    rules.forEach((rule) => {
      const [attr, key] = rule.split(':').map((part) => part.trim());
      const value = getNestedValue(data, key);
      if (attr && typeof value === 'string') {
        el.setAttribute(attr, value);
      }
    });
  });

  document.querySelectorAll('.lang-switch button[data-lang]').forEach((btn) => {
    btn.classList.toggle('active', btn.dataset.lang === selected);
  });

  window.localStorage.setItem('site_lang', selected);
}

(function initLanguage() {
  const saved = window.localStorage.getItem('site_lang');
  const startLang = saved || 'en';
  applyLanguage(startLang);

  document.querySelectorAll('.lang-switch button[data-lang]').forEach((btn) => {
    btn.addEventListener('click', () => {
      applyLanguage(btn.dataset.lang);
    });
  });
})();

(function initMenu() {
  const menuButton = document.querySelector('.menu-toggle');
  const nav = document.querySelector('.navbar');

  if (!menuButton || !nav) {
    return;
  }

  menuButton.addEventListener('click', () => {
    const isOpen = nav.classList.toggle('open');
    menuButton.setAttribute('aria-expanded', String(isOpen));
  });
})();

(function initCarousel() {
  const carousel = document.querySelector('[data-carousel]');
  if (!carousel) {
    return;
  }

  const slides = Array.from(carousel.querySelectorAll('.slide'));
  const nextBtn = carousel.querySelector('.next');
  const prevBtn = carousel.querySelector('.prev');
  let index = 0;

  function showSlide(nextIndex) {
    slides[index].classList.remove('active');
    index = (nextIndex + slides.length) % slides.length;
    slides[index].classList.add('active');
  }

  nextBtn.addEventListener('click', () => showSlide(index + 1));
  prevBtn.addEventListener('click', () => showSlide(index - 1));

  setInterval(() => {
    showSlide(index + 1);
  }, 5000);
})();
